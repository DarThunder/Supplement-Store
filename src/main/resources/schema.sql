
CREATE TABLE IF NOT EXISTS CATEGORY (
    ID_CATEGORY INT AUTO_INCREMENT PRIMARY KEY,
    CAT_NAME VARCHAR(100) NOT NULL,
    CAT_DESC TEXT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PRODUCT (
    ID_PRODUCT INT AUTO_INCREMENT PRIMARY KEY,
    ID_CATEGORY INT NOT NULL,
    PROD_NAME VARCHAR(150) NOT NULL,
    PROD_DESC TEXT,
    PRICE DECIMAL(10,2) NOT NULL,
    STOCK INT NOT NULL DEFAULT 0,

    CONSTRAINT fk_product_category
        FOREIGN KEY (ID_CATEGORY)
        REFERENCES CATEGORY(ID_CATEGORY),

    CONSTRAINT chk_product_price
        CHECK (PRICE >= 0),

    CONSTRAINT chk_product_stock
        CHECK (STOCK >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SALE (
    ID_SALE INT AUTO_INCREMENT PRIMARY KEY,
    SALE_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TOTAL_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0.00
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SALE_DETAIL (
    ID_DETAIL INT AUTO_INCREMENT PRIMARY KEY,
    ID_SALE INT NOT NULL,
    ID_PRODUCT INT NOT NULL,
    AMOUNT INT NOT NULL,
    UNITARY_PRICE DECIMAL(10,2) NOT NULL,
    SUBTOTAL DECIMAL(12,2) NOT NULL,

    CONSTRAINT fk_detail_sale
        FOREIGN KEY (ID_SALE)
        REFERENCES SALE(ID_SALE)
        ON DELETE CASCADE,

    CONSTRAINT fk_detail_product
        FOREIGN KEY (ID_PRODUCT)
        REFERENCES PRODUCT(ID_PRODUCT),

    CONSTRAINT chk_detail_amount
        CHECK (AMOUNT > 0),

    CONSTRAINT chk_detail_price
        CHECK (UNITARY_PRICE >= 0),

    CONSTRAINT chk_detail_subtotal
        CHECK (SUBTOTAL >= 0)
) ENGINE=InnoDB;
